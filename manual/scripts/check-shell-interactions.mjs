import assert from 'node:assert/strict'
import path from 'node:path'
import { expect } from 'playwright/test'

async function noOverflow(page) {
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'Page must fit the viewport')
}
async function unlocked(page) {
  await expect(page.locator('body')).not.toHaveClass(/manual-menu-open/)
  assert.ok(await page.evaluate(() => getComputedStyle(document.body).overflow !== 'hidden'), 'Page scrolling must be restored')
}
async function fitsDiagram(page) {
  await expect.poll(() => page.locator('.diagram-modal-body img').evaluate(img => img.complete && img.naturalWidth > 0)).toBe(true)
  await expect.poll(() => page.locator('.diagram-modal-body').evaluate(viewer => {
    const img = viewer.querySelector('img').getBoundingClientRect()
    const r = viewer.getBoundingClientRect()
    const style = getComputedStyle(viewer)
    const width = viewer.clientWidth - parseFloat(style.paddingLeft) - parseFloat(style.paddingRight)
    const height = viewer.clientHeight - parseFloat(style.paddingTop) - parseFloat(style.paddingBottom)
    return img.width > 0 && Math.max(img.width / width, img.height / height) > 0.9 && img.left >= r.left && img.right <= r.right + 1 && img.top >= r.top && img.bottom <= r.bottom + 1
  })).toBe(true)
}

export async function checkDesktopShell(page, origin, output) {
  await page.goto(`${origin}/manual/`)
  const side = page.locator('.docs-sidebar')
  const groups = side.getByRole('link', { name: '用户组、默认通道与费率', exact: true })
  const location = page.url()
  await side.getByRole('button', { name: '展开商户与用户组', exact: true }).click()
  await expect(groups).toBeVisible()
  assert.equal(page.url(), location, 'Expanding a module must not navigate')
  const toggle = side.getByRole('button', { name: '收起商户与用户组', exact: true })
  await toggle.focus()
  await page.keyboard.press('Space')
  await expect(groups).not.toBeVisible()
  await page.keyboard.press('Enter')
  await expect(groups).toBeVisible()
  await groups.click()
  await expect(page.locator('.vp-doc h1')).toContainText('用户组')
  await expect(groups).toHaveAttribute('aria-current', 'page')
  await side.getByRole('link', { name: '商户与用户组', exact: true }).click()
  await expect(page).toHaveURL(`${origin}/manual/modules/merchant-management.html`)
  await page.goBack()
  await expect(groups).toHaveAttribute('aria-current', 'page')
  await expect(groups).toBeVisible()
  await page.goForward()
  await expect(side.getByRole('link', { name: '商户与用户组', exact: true })).toHaveAttribute('aria-current', 'page')
  await page.screenshot({ path: path.join(output, 'manual-sidebar-desktop.png'), animations: 'disabled' })
  const anchor = page.locator('.docs-toc nav a').nth(1)
  const hash = await anchor.getAttribute('href')
  await anchor.click()
  await expect.poll(() => page.evaluate(id => document.getElementById(id)?.getBoundingClientRect().top, decodeURIComponent(hash.slice(1)))).toBeGreaterThanOrEqual(90)
  await expect(anchor).toHaveClass(/active/)
  await page.getByRole('button', { name: '关闭顶部提示', exact: true }).click()
  await expect.poll(() => page.locator('.docs-header').evaluate(el => el.getBoundingClientRect().top)).toBe(0)
  await expect.poll(() => side.evaluate(el => el.getBoundingClientRect().top)).toBe(60)
  await page.keyboard.press('Control+k')
  const input = page.locator('#localsearch-input')
  await expect(input).toBeFocused()
  await input.fill('zznomatch123456789')
  await expect(page.locator('.VPLocalSearchBox .no-results')).toContainText('没有找到相关内容')
  await page.getByRole('button', { name: '清空搜索', exact: true }).click()
  await expect(input).toHaveValue('')
  await input.fill('默认通道')
  await expect(page.locator('.VPLocalSearchBox a.result[href*="admin/groups"]').first()).toBeVisible()
  await page.locator('.VPLocalSearchBox a.result[href*="admin/groups"]').first().click()
  await expect(page).toHaveURL(/\/manual\/admin\/groups.html/)
  await expect(page.locator('.VPLocalSearchBox')).toHaveCount(0)
  await expect(groups).toBeVisible()
  await unlocked(page)
  await page.goto(`${origin}/manual/404.html`)
  await expect(page.getByRole('heading', { name: '没有找到这篇文档' })).toBeVisible()
  await page.getByRole('link', { name: '返回文档首页 →', exact: true }).click()
  await expect(page.locator('.vp-doc h1')).toHaveText('快速开始')
}

export async function checkResponsiveShell(page, origin, output) {
  await page.goto(`${origin}/manual/concepts/architecture.html`)
  const menu = page.getByRole('button', { name: '目录', exact: true })
  const sidebar = page.locator('.docs-sidebar')
  for (const width of [320, 375, 640, 768, 1024, 1280, 1440]) {
    await page.setViewportSize({ width, height: 900 })
    await noOverflow(page)
    assert.ok(await page.locator('.docs-header').evaluate(header => {
      const children = [...header.children].filter(el => el.getClientRects().length).map(el => el.getBoundingClientRect())
      return children.every((r, i) => r.left >= 0 && r.right <= innerWidth && (!i || r.left >= children[i - 1].right))
    }), `Header controls overlap at ${width}px`)
  }
  await page.setViewportSize({ width: 375, height: 900 })
  await menu.click()
  const close = sidebar.getByRole('button', { name: '关闭目录', exact: true })
  await expect(close).toBeFocused()
  await expect(sidebar).toHaveAttribute('aria-modal', 'true')
  await expect(page.locator('.docs-main')).toHaveAttribute('inert', '')
  await page.keyboard.press('Shift+Tab')
  assert.ok(await sidebar.evaluate(el => el.contains(document.activeElement)), 'Keyboard focus escaped the mobile drawer')
  await page.keyboard.press('Tab')
  await expect(close).toBeFocused()
  await page.screenshot({ path: path.join(output, 'manual-mobile-sidebar.png'), animations: 'disabled' })
  await page.keyboard.press('Escape')
  await expect(sidebar).not.toBeVisible()
  await expect(menu).toBeFocused()
  await unlocked(page)
  await menu.click()
  await page.locator('.docs-backdrop').click({ position: { x: 340, y: 200 } })
  await expect(sidebar).not.toBeVisible()
  await expect(menu).toBeFocused()
  await menu.click()
  await close.click()
  await expect(sidebar).not.toBeVisible()
  await menu.click()
  await page.setViewportSize({ width: 1440, height: 900 })
  await expect(sidebar).not.toHaveClass(/open/)
  await unlocked(page)
  await expect(page.locator('.docs-main')).not.toHaveAttribute('inert', '')
  await page.setViewportSize({ width: 375, height: 900 })
  await expect(sidebar).not.toBeVisible()
  await menu.click()
  await page.keyboard.press('Control+k')
  const input = page.locator('#localsearch-input')
  await expect(input).toBeFocused()
  await expect(sidebar).not.toBeVisible()
  await input.fill('退款')
  await expect(page.locator('.VPLocalSearchBox a.result').first()).toBeVisible()
  await page.screenshot({ path: path.join(output, 'manual-mobile-search.png'), animations: 'disabled' })
  await page.keyboard.press('ArrowDown')
  await page.keyboard.press('Enter')
  await expect(page.locator('.VPLocalSearchBox')).toHaveCount(0)
  await unlocked(page)
  await noOverflow(page)
  const toc = page.getByRole('button', { name: '本页内容', exact: false })
  await toc.click()
  await expect(page.locator('.mobile-toc')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(toc).toBeFocused()
  await expect(page.locator('.mobile-toc')).toHaveCount(0)
  await toc.click()
  await page.locator('.mobile-toc a').first().click()
  await expect(page.locator('.mobile-toc')).toHaveCount(0)
  await page.getByRole('switch', { name: '切换到深色模式', exact: true }).click()
  await expect(page.locator('html')).toHaveClass(/dark/)
  await page.screenshot({ path: path.join(output, 'manual-mobile-dark.png'), animations: 'disabled' })
  await page.getByRole('switch', { name: '切换到浅色模式', exact: true }).click()
  await page.goto(`${origin}/manual/concepts/payment-flow.html`)
  await page.setViewportSize({ width: 844, height: 390 })
  const open = page.getByRole('button', { name: /^放大时序图/ })
  await open.click()
  await fitsDiagram(page)
  await page.getByRole('button', { name: '放大图表', exact: true }).click()
  await page.getByRole('button', { name: '适合窗口', exact: true }).click()
  await fitsDiagram(page)
  await page.screenshot({ path: path.join(output, 'manual-diagram-landscape-fit.png'), animations: 'disabled' })
  await page.setViewportSize({ width: 375, height: 900 })
  await fitsDiagram(page)
  await page.getByRole('button', { name: '关闭图表', exact: true }).focus()
  await page.keyboard.press('Tab')
  await expect(page.getByRole('button', { name: '缩小图表', exact: true })).toBeFocused()
  await page.keyboard.press('Shift+Tab')
  await expect(page.getByRole('button', { name: '关闭图表', exact: true })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(open).toBeFocused()
  await unlocked(page)
}
