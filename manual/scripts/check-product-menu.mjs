import assert from 'node:assert/strict'
import path from 'node:path'
import { expect } from 'playwright/test'

export async function checkProductMenu(page, origin, output) {
  const product = page.locator('.docs-product')
  const trigger = product.locator('summary')
  const options = product.locator('.docs-product-options')
  const isClosed = () => expect(product).not.toHaveAttribute('open', '')
  await page.goto(`${origin}/manual/`)
  await trigger.click()
  await expect(options).toBeVisible()
  // Hit testing catches stacking-context regressions over both sidebar and article.
  assert.ok(await options.locator('a').evaluateAll(links => links.every(link => {
    const rect = link.getBoundingClientRect()
    return link.contains(document.elementFromPoint(rect.x + rect.width / 2, rect.y + rect.height / 2))
  })), 'Product links must be above the sidebar and article')
  await page.screenshot({ path: path.join(output, 'manual-product-menu-light.png'), animations: 'disabled' })
  await page.locator('.vp-doc h1').click()
  await isClosed()
  await trigger.click()
  await page.keyboard.press('Escape')
  await isClosed()
  await expect(trigger).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(options).toBeVisible()
  await page.keyboard.press('Tab')
  await expect(options.locator('a').first()).toBeFocused()
  await expect(options).toBeVisible()
  await page.keyboard.press('Shift+Tab')
  await expect(trigger).toBeFocused()
  await page.keyboard.press('Shift+Tab')
  await isClosed()
  await trigger.click()
  await options.getByRole('link', { name: '全部功能模块', exact: true }).click()
  await isClosed()
  await trigger.click()
  await options.getByRole('link', { name: '管理员快速开始', exact: true }).click()
  await expect(page).toHaveURL(`${origin}/manual/admin/quickstart.html`)
  await isClosed()
  await trigger.click()
  await options.getByRole('link', { name: '商户快速开始', exact: true }).click()
  await expect(page).toHaveURL(`${origin}/manual/merchant/quickstart.html`)
  await isClosed()
  await page.getByRole('switch', { name: '切换到深色模式', exact: true }).click()
  await trigger.click()
  await expect(options).toBeVisible()
  await page.screenshot({ path: path.join(output, 'manual-product-menu-dark.png'), animations: 'disabled' })
  // Opening a higher layer also dismisses the disclosure without intercepting the click.
  await page.getByRole('button', { name: '搜索使用手册', exact: true }).click()
  await isClosed()
  await expect(page.locator('#localsearch-input')).toBeVisible()
  assert.ok(await page.locator('#localsearch-input').evaluate(el => {
    const r = el.getBoundingClientRect()
    return el.contains(document.elementFromPoint(r.x + r.width / 2, r.y + r.height / 2))
  }))
  await page.keyboard.press('Escape')
  await page.getByRole('switch', { name: '切换到浅色模式', exact: true }).click()
  for (const width of [768, 375]) {
    await trigger.click()
    await page.setViewportSize({ width, height: 900 })
    await expect(product).not.toBeVisible()
    await isClosed()
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1))
    await page.setViewportSize({ width: 1440, height: 1000 })
    await isClosed()
  }
  await page.goto(`${origin}/manual/`)
}
