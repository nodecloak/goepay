CREATE TABLE payment_subchannels (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 merchant_id bigint NOT NULL REFERENCES merchants(id),
 parent_id bigint NOT NULL CHECK(parent_id>0),
 pay_type text NOT NULL CHECK(pay_type IN ('alipay','wxpay')),
 name text NOT NULL CHECK(length(name) BETWEEN 1 AND 120),
 enabled boolean NOT NULL DEFAULT false,
 archived boolean NOT NULL DEFAULT false CHECK(NOT archived OR NOT enabled),
 weight bigint NOT NULL DEFAULT 1 CHECK(weight BETWEEN 1 AND 99),
 min_amount bigint NOT NULL DEFAULT 0 CHECK(min_amount>=0),
 max_amount bigint NOT NULL DEFAULT 0 CHECK(max_amount>=0 AND (max_amount=0 OR max_amount>=min_amount)),
 revision bigint NOT NULL CHECK(revision>0),
 account_version bigint NOT NULL CHECK(account_version>0),
 proof_hash bytea NOT NULL CHECK(octet_length(proof_hash)=32),
 created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
 updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),
 UNIQUE(id,merchant_id)
);
CREATE TABLE payment_subchannel_accounts (
 subchannel_id bigint NOT NULL,
 version bigint NOT NULL CHECK(version>0),
 merchant_id bigint NOT NULL,
 parent_id bigint NOT NULL CHECK(parent_id>0),
 pay_type text NOT NULL CHECK(pay_type IN ('alipay','wxpay')),
 schema_hash text NOT NULL CHECK(schema_hash ~ '^[0-9a-f]{64}$'),
 nonce bytea NOT NULL CHECK(octet_length(nonce)=12),
 ciphertext bytea NOT NULL CHECK(octet_length(ciphertext)>=16),
 proof_hash bytea NOT NULL CHECK(octet_length(proof_hash)=32),
 created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
 PRIMARY KEY(subchannel_id,version),
 UNIQUE(subchannel_id,version,merchant_id,parent_id),
 FOREIGN KEY(subchannel_id,merchant_id) REFERENCES payment_subchannels(id,merchant_id)
);
ALTER TABLE payment_subchannels ADD CONSTRAINT payment_subchannel_current_account_fk FOREIGN KEY(id,account_version) REFERENCES payment_subchannel_accounts(subchannel_id,version) DEFERRABLE INITIALLY DEFERRED;
CREATE TABLE payment_subchannel_merchant_policy (
 merchant_id bigint PRIMARY KEY REFERENCES merchants(id),
 roll_type int NOT NULL CHECK(roll_type BETWEEN 0 AND 3),
 revision bigint NOT NULL CHECK(revision>0),
 proof_hash bytea NOT NULL CHECK(octet_length(proof_hash)=32)
);
CREATE TABLE payment_subchannel_routes (
 merchant_id bigint NOT NULL,
 out_trade_no text NOT NULL,
 parent_id bigint NOT NULL,
 subchannel_id bigint NOT NULL,
 account_version bigint NOT NULL,
 account_proof bytea NOT NULL CHECK(octet_length(account_proof)=32),
 execution_identity bytea NOT NULL CHECK(octet_length(execution_identity)=32),
 account_hash bytea NOT NULL CHECK(octet_length(account_hash)=32),
 product text NOT NULL CHECK(length(product)>0),
 proof_hash bytea NOT NULL CHECK(octet_length(proof_hash)=32),
 selected_at timestamptz NOT NULL DEFAULT clock_timestamp(),
 PRIMARY KEY(merchant_id,out_trade_no),
 FOREIGN KEY(merchant_id,out_trade_no,parent_id) REFERENCES provider_route_assignments(merchant_id,out_trade_no,channel_id),
 FOREIGN KEY(subchannel_id,account_version,merchant_id,parent_id) REFERENCES payment_subchannel_accounts(subchannel_id,version,merchant_id,parent_id)
);
CREATE TABLE payment_subchannel_last_used (
 subchannel_id bigint PRIMARY KEY REFERENCES payment_subchannels(id),
 merchant_id bigint NOT NULL,
 out_trade_no text NOT NULL,
 used_millis bigint NOT NULL CHECK(used_millis>=0),
 FOREIGN KEY(merchant_id,out_trade_no) REFERENCES payment_subchannel_routes(merchant_id,out_trade_no)
);
CREATE FUNCTION payment_subchannel_immutable() RETURNS trigger LANGUAGE plpgsql AS $$BEGIN RAISE EXCEPTION 'immutable payment subchannel source';END$$;
CREATE TRIGGER payment_subchannel_account_immutable BEFORE UPDATE OR DELETE ON payment_subchannel_accounts FOR EACH ROW EXECUTE FUNCTION payment_subchannel_immutable();
CREATE TRIGGER payment_subchannel_route_immutable BEFORE UPDATE OR DELETE ON payment_subchannel_routes FOR EACH ROW EXECUTE FUNCTION payment_subchannel_immutable();
CREATE FUNCTION payment_subchannel_owner_immutable() RETURNS trigger LANGUAGE plpgsql AS $$BEGIN IF NEW.id<>OLD.id OR NEW.merchant_id<>OLD.merchant_id THEN RAISE EXCEPTION 'immutable payment subchannel owner'; END IF;RETURN NEW;END$$;
CREATE TRIGGER payment_subchannel_owner_immutable BEFORE UPDATE ON payment_subchannels FOR EACH ROW EXECUTE FUNCTION payment_subchannel_owner_immutable();
CREATE INDEX payment_subchannels_owned ON payment_subchannels(merchant_id,pay_type,id);
CREATE INDEX payment_subchannel_routes_child ON payment_subchannel_routes(subchannel_id,selected_at);
CREATE FUNCTION payment_subchannel_head_source() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE source_child bigint; source_millis bigint;
BEGIN
 SELECT subchannel_id,floor(extract(epoch FROM selected_at)*1000)::bigint INTO source_child,source_millis FROM payment_subchannel_routes WHERE merchant_id=NEW.merchant_id AND out_trade_no=NEW.out_trade_no;
 IF NOT FOUND OR source_child<>NEW.subchannel_id OR source_millis<>NEW.used_millis THEN RAISE EXCEPTION 'child head requires its immutable selected route';END IF;
 IF TG_OP='UPDATE' AND NEW.subchannel_id<>OLD.subchannel_id THEN RAISE EXCEPTION 'child head identity cannot change';END IF;RETURN NEW;
END $$;
CREATE TRIGGER payment_subchannel_head_source BEFORE INSERT OR UPDATE ON payment_subchannel_last_used FOR EACH ROW EXECUTE FUNCTION payment_subchannel_head_source();
CREATE TRIGGER payment_subchannel_head_no_delete BEFORE DELETE ON payment_subchannel_last_used FOR EACH ROW EXECUTE FUNCTION payment_subchannel_immutable();
