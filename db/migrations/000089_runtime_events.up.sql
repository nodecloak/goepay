CREATE TABLE runtime_events (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 created_at timestamptz NOT NULL DEFAULT now(),
 level text NOT NULL CHECK (level IN ('debug','info','notice','warning','error','critical','alert','emergency','sql')),
 content text NOT NULL CHECK (octet_length(content) BETWEEN 1 AND 4096),
 error_code text NOT NULL CHECK (error_code ~ '^[A-Z0-9_]{1,32}$'),
 archived_at timestamptz
);
CREATE INDEX runtime_events_visible_time ON runtime_events(created_at DESC,id DESC) WHERE archived_at IS NULL;
COMMENT ON TABLE runtime_events IS 'Sanitized local application runtime events; operational archive is independent from immutable financial and business audits';
