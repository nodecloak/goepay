-- A preparation freezes an explicit selection; it does not reserve or send funds.
CREATE TABLE order_business_batches (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 actor_id bigint NOT NULL CHECK(actor_id>0),
 actor_name text NOT NULL CHECK(length(actor_name) BETWEEN 1 AND 128),
 external_no text NOT NULL CHECK(length(external_no) BETWEEN 8 AND 96),
 action text NOT NULL CHECK(action IN ('query','notify','refund','freeze-income','unfreeze-income','confirm-settlement')),
 reason text NOT NULL CHECK(length(reason) BETWEEN 1 AND 240),
 item_count integer NOT NULL CHECK(item_count BETWEEN 1 AND 100),
 request_hash bytea NOT NULL CHECK(octet_length(request_hash)=32),
 source_hash bytea NOT NULL CHECK(octet_length(source_hash)=32),
 created_at timestamptz NOT NULL,
 UNIQUE(actor_id,actor_name,external_no)
);
CREATE TABLE order_business_batch_items (
 batch_id bigint NOT NULL REFERENCES order_business_batches(id),
 position integer NOT NULL CHECK(position BETWEEN 1 AND 100),
 order_id bigint NOT NULL REFERENCES orders(id),
 merchant_id bigint NOT NULL REFERENCES merchants(id),
 trade_no text NOT NULL CHECK(length(trade_no) BETWEEN 1 AND 64),
 source jsonb NOT NULL CHECK(jsonb_typeof(source)='object'),
 PRIMARY KEY(batch_id,position),
 UNIQUE(batch_id,order_id)
);
CREATE TABLE order_business_batch_events (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 batch_id bigint NOT NULL REFERENCES order_business_batches(id),
 event_no bigint NOT NULL CHECK(event_no>0),
 position integer NOT NULL CHECK(position BETWEEN 0 AND 100),
 event_type text NOT NULL CHECK(event_type IN ('authorize','claim','result','cancel','finish')),
 facts jsonb NOT NULL CHECK(jsonb_typeof(facts)='object'),
 previous_hash bytea NOT NULL CHECK(octet_length(previous_hash)=32),
 proof_hash bytea NOT NULL CHECK(octet_length(proof_hash)=32),
 created_at timestamptz NOT NULL,
 UNIQUE(batch_id,event_no)
);
CREATE TRIGGER order_business_batch_immutable BEFORE UPDATE OR DELETE ON order_business_batches FOR EACH ROW EXECUTE FUNCTION reject_ledger_mutation();
CREATE TRIGGER order_business_batch_item_immutable BEFORE UPDATE OR DELETE ON order_business_batch_items FOR EACH ROW EXECUTE FUNCTION reject_ledger_mutation();
CREATE TRIGGER order_business_batch_event_immutable BEFORE UPDATE OR DELETE ON order_business_batch_events FOR EACH ROW EXECUTE FUNCTION reject_ledger_mutation();
